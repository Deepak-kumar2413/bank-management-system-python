class Account:
    def __init__(self, acc_no, name, balance):
        self.acc_no = acc_no
        self.name = name
        self.balance = balance
        self.transaction = []

    # Deposit Money
    def deposit(self, amount):
        if amount > 0:
            self.balance += amount
            self.transaction.append(f"Deposited Rs. {amount}")
            print("Amount Deposited Successfully")
        else:
            print("Invalid Amount")

    # Withdraw Money
    def withdraw(self, amount):
        if amount <= 0:
            print("Invalid Amount")
        elif amount <= self.balance:
            self.balance -= amount
            self.transaction.append(f"Withdraw Rs. {amount}")
            print("Withdraw Successful")
        else:
            print("Insufficient Money!")

    # Transfer Money
    def transfer(self, receiver, amount):
        if amount <= 0:
            print("Invalid Amount")
        elif amount <= self.balance:
            self.balance -= amount
            receiver.balance += amount

            self.transaction.append(
                f"Transferred Rs. {amount} to {receiver.acc_no}"
            )
            receiver.transaction.append(
                f"Received Rs. {amount} from {self.acc_no}"
            )
            print("Transfer Successful")
        else:
            print("Insufficient Money!")

    # Transaction History
    def show_transaction(self):
        print("\n----- Transaction History -----")
        if self.transaction:
            for t in self.transaction:
                print(t)
        else:
            print("No Transaction Found")

    # Check Balance
    def check_balance(self):
        print(f"Current Balance: Rs. {self.balance}")

    # Display Account Details
    def display(self):
        print("\n-------------------")
        print(f"Account No: {self.acc_no}")
        print(f"Name: {self.name}")
        print(f"Balance: Rs. {self.balance}")


# Store All Accounts
accounts = {}

while True:
    print("\n===== BANK MANAGEMENT SYSTEM =====")
    print("1. Create Account")
    print("2. Deposit Money")
    print("3. Withdraw Money")
    print("4. Transfer Money")
    print("5. View Transaction History")
    print("6. Check Balance")
    print("7. Display All Accounts")
    print("8. Exit")

    choice = input("Enter Your Choice: ")

    # 1. Create Account
    if choice == "1":
        acc_no = input("Enter Account Number: ")

        if acc_no in accounts:
            print("Account Already Exists")
        else:
            name = input("Enter Name: ")
            balance = float(input("Enter Initial Balance: "))

            if balance < 0:
                print("Invalid Balance")
            else:
                accounts[acc_no] = Account(acc_no, name, balance)
                print("Account Created Successfully")

    # 2. Deposit Money
    elif choice == "2":
        acc_no = input("Enter Account Number: ")

        if acc_no in accounts:
            amount = float(input("Enter Amount: "))
            accounts[acc_no].deposit(amount)
        else:
            print("Account Not Found")

    # 3. Withdraw Money
    elif choice == "3":
        acc_no = input("Enter Account Number: ")

        if acc_no in accounts:
            amount = float(input("Enter Amount: "))
            accounts[acc_no].withdraw(amount)
        else:
            print("Account Not Found")

    # 4. Transfer Money
    elif choice == "4":
        sender = input("Enter Sender Account Number: ")
        receiver = input("Enter Receiver Account Number: ")

        if sender in accounts and receiver in accounts:
            if sender == receiver:
                print("Cannot Transfer to Same Account")
            else:
                amount = float(input("Enter Amount: "))
                accounts[sender].transfer(accounts[receiver], amount)
        else:
            print("Account Not Found")

    # 5. Transaction History
    elif choice == "5":
        acc_no = input("Enter Account Number: ")

        if acc_no in accounts:
            accounts[acc_no].show_transaction()
        else:
            print("Account Not Found")

    # 6. Check Balance
    elif choice == "6":
        acc_no = input("Enter Account Number: ")

        if acc_no in accounts:
            accounts[acc_no].check_balance()
        else:
            print("Account Not Found")

    # 7. Display All Accounts
    elif choice == "7":
        if accounts:
            for acc in accounts.values():
                acc.display()
        else:
            print("No Accounts Found")

    # 8. Exit
    elif choice == "8":
        print("Thank You for Using Bank System")
        break

    else:
        print("Invalid Choice")